package budgetguard;

import budgetguard.BudgetGuard.GuardConfig;
import budgetguard.BudgetGuard.RunResult;
import org.neuroph.core.data.DataSet;
import org.neuroph.core.data.DataSetRow;

import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Runs every experiment reported in the project report and writes CSV tables plus a Markdown summary.
 * Usage: java -jar dist/autoscalesim-lab.jar evaluate [--out docs/results]
 * All numbers come from real AutoScaleSim runs or from the documented forecasting code.
 */
public final class Evaluate {

    static final double RATE = BudgetGuard.DEFAULT_INR_PER_USD;
    static final String[] METRIC_KEYS = {"total_requests", "response_time_avg_s", "delay_time_avg_s", "sla_violation_pct", "cpu_util_avg_pct",
            "max_vms", "vms_provisioned", "contradictory_decisions", "cloudlets_failed", "renting_cost_usd", "sla_penalty_usd", "total_cost_usd"};

    public static void run(Path dataDir, Path out, PrintStream log) throws Exception {
        Files.createDirectories(out);
        Path work = Files.createTempDirectory("autoscalesim-eval");
        StringBuilder md = new StringBuilder("# Evaluation results\n\nGenerated by `BudgetGuard evaluate` on " + java.time.LocalDate.now()
                + ". Exchange-rate assumption: ₹" + RATE + " per US$ (the simulator reports US$). Every row is a real simulation or a documented calculation.\n\n");
        GuardConfig cfg = new GuardConfig(2000, 4.0, RATE);

        // ------------------------------------------------------------ E1 reproduction
        log.println("E1 reproduction");
        RunResult nasa = BudgetGuard.runChild("original", cfg, dataDir, work.resolve("e1_nasa"), log);
        RunResult wiki = BudgetGuard.runChild("observe", cfg, BudgetGuard.Scenario.wikipediaDocumented(), dataDir, work.resolve("e1_wiki"), null, log);
        List<String[]> e1 = new ArrayList<>();
        e1.add(new String[]{"metric", "nasa_original_main", "wikipedia_documented_values"});
        for (String k : METRIC_KEYS) e1.add(new String[]{k, val(nasa.metrics.get(k)), val(wiki.metrics.get(k))});
        BudgetGuard.Csv.write(out.resolve("e1_reproduction.csv"), e1);
        md.append("## E1 Reproduction\n\n");
        for (String f : new String[]{"Monitor_VmHistory.csv", "Monitor_SLAHistory.csv", "Monitor_EndUserHistory.csv"})
            md.append("- `").append(f).append("` identical to the authors' committed file: **")
                    .append(BudgetGuard.sameFile(dataDir.resolve(f), nasa.dir.resolve("src/others/" + f)) ? "yes" : "NO").append("**\n");
        md.append("\n").append(table(e1)).append("\n");

        // ------------------------------------------------------------ E2 budget sweep
        log.println("E2 budget sweep");
        double[] budgets = {500, 750, 1000, 1250, 1500, 1750, 2000, 2250, 2500, 2750, 3000};
        Path sw = work.resolve("e2_sweep");
        BudgetGuard.sweep(budgets, 4.0, RATE, dataDir, sw, log);
        List<String[]> e2 = BudgetGuard.Csv.read(sw.resolve("sweep.csv"));
        BudgetGuard.Csv.write(out.resolve("e2_budget_sweep.csv"), e2);
        md.append("## E2 Budget sweep (NASA 7 days, response-time target 4 s)\n\n").append(table(e2)).append("\n");

        // ------------------------------------------------------------ E3 replay fidelity
        log.println("E3 replay fidelity");
        DataSet d = DataSet.load(dataDir.resolve("Dataset_NASA_July.tset").toString());
        DataSet copy = new DataSet(5, d.getOutputSize());
        for (int i = 0; i < 7 * 1440; i++) copy.addRow(new DataSetRow(d.getRowAt(i).getInput().clone(), d.getRowAt(i).getDesiredOutput().clone()));
        Path exact = work.resolve("exact.tset");
        copy.save(exact.toString());
        double[] week1 = Workload.nasaMinutes(dataDir.resolve("Dataset_NASA_July.tset"), 0, 7 * 1440);
        Workload w1 = new Workload("NASA week 1", "per-minute counts", week1);
        BudgetGuard.Scenario sc = BudgetGuard.Scenario.nasaDefault();
        List<String[]> e3 = new ArrayList<>();
        e3.add(new String[]{"replay", "response_time_avg_s", "sla_violation_pct", "max_vms", "renting_cost_inr", "total_requests"});
        e3.add(row3("authors' original run", nasa));
        e3.add(row3("exact copy of the original rows", BudgetGuard.runChild("observe", cfg, sc, dataDir, work.resolve("e3_exact"), exact, log)));
        for (long seed : new long[]{Workload.ARRIVAL_SEED, 1, 2}) {
            Path t = work.resolve("u" + seed + ".tset");
            w1.writeTset(t, Workload.ARRIVALS_RANDOM_UNIFORM, seed);
            e3.add(row3("per-minute counts, random-uniform arrivals (seed " + seed + ")", BudgetGuard.runChild("observe", cfg, sc, dataDir, work.resolve("e3_u" + seed), t, log)));
        }
        Path ev = work.resolve("even.tset");
        w1.writeTset(ev, Workload.ARRIVALS_EVEN);
        e3.add(row3("per-minute counts, evenly spaced arrivals", BudgetGuard.runChild("observe", cfg, sc, dataDir, work.resolve("e3_even"), ev, log)));
        BudgetGuard.Csv.write(out.resolve("e3_replay_fidelity.csv"), e3);
        md.append("## E3 Fidelity of replaying per-minute workloads (NASA week 1, original policy)\n\n").append(table(e3)).append("\n");

        // ------------------------------------------------------------ E4 forecasting and spike warnings
        log.println("E4 forecasting");
        List<String[]> e4 = new ArrayList<>();
        e4.add(new String[]{"workload", "lead_min", "model", "mae_model", "mae_last_value", "mae_seasonal_naive", "spikes", "warnings", "precision", "recall"});
        List<Object[]> sets = new ArrayList<>();
        for (int wk = 2; wk <= 4; wk++)
            sets.add(new Object[]{"NASA week " + wk + " (real)", Workload.nasaMinutes(dataDir.resolve("Dataset_NASA_July.tset"), (wk - 1) * 7 * 1440, wk * 7 * 1440)});
        Path flash = Path.of("samples/synthetic_flash_crowd_3days.csv");
        if (Files.exists(flash))
            sets.add(new Object[]{"flash crowd (synthetic)", Workload.parse("flash", new String(Files.readAllBytes(flash), StandardCharsets.UTF_8)).perMinute});
        for (Object[] set : sets) {
            Workload w = new Workload((String) set[0], "per-minute counts", (double[]) set[1]);
            for (int lead : new int[]{1, 2, 3, 6}) {
                Workload.Params p = new Workload.Params();
                p.leadBuckets = lead;
                Map<String, Object> s = w.analyse(p).summary;
                e4.add(new String[]{w.name, String.valueOf(lead * 10), lead == 1 ? (String) s.get("model") : "same family",
                        str(s.get("mae_model")), str(s.get("mae_naive_last_value")), str(s.get("mae_seasonal_naive")),
                        str(s.get("spikes_detected")), str(s.get("warnings_issued")), str(s.get("warning_precision")), str(s.get("warning_recall"))});
            }
        }
        BudgetGuard.Csv.write(out.resolve("e4_forecast_backtest.csv"), e4);
        md.append("## E4 Forecast accuracy and spike-warning backtest (10-minute buckets, k = 2.5)\n\n").append(table(e4)).append("\n");

        // ------------------------------------------------------------ E5 capacity estimate vs simulation
        log.println("E5 capacity estimate vs simulation");
        List<String[]> e5 = new ArrayList<>();
        e5.add(new String[]{"workload", "estimated_max_vms", "simulated_max_vms", "estimated_cost_inr", "simulated_renting_cost_inr", "simulated_avg_rt_s", "simulated_sla_violation_pct"});
        for (int wk = 1; wk <= 4; wk++) {
            Workload w = new Workload("NASA week " + wk, "per-minute counts", Workload.nasaMinutes(dataDir.resolve("Dataset_NASA_July.tset"), (wk - 1) * 7 * 1440, wk * 7 * 1440));
            Map<String, Object> s = w.analyse(new Workload.Params()).summary;
            RunResult r = BudgetGuard.simulateWorkload(w, cfg, false, dataDir, work.resolve("e5_w" + wk), log).get(0);
            e5.add(new String[]{w.name, str(s.get("max_required_vms_observed")), val(r.metrics.get("max_vms")), str(s.get("estimated_cost_observed_inr")),
                    fmt(r.metrics.get("renting_cost_usd") * RATE), val(r.metrics.get("response_time_avg_s")), val(r.metrics.get("sla_violation_pct"))});
        }
        BudgetGuard.Csv.write(out.resolve("e5_capacity_estimate.csv"), e5);
        md.append("## E5 Capacity and cost estimate vs AutoScaleSim (original policy, random-uniform replay)\n\n").append(table(e5)).append("\n");

        Files.write(out.resolve("RESULTS.md"), md.toString().getBytes(StandardCharsets.UTF_8));
        log.println("Evaluation written to " + out.toAbsolutePath());
    }

    static String[] row3(String name, RunResult r) {
        return new String[]{name, val(r.metrics.get("response_time_avg_s")), val(r.metrics.get("sla_violation_pct")), val(r.metrics.get("max_vms")),
                fmt(r.metrics.get("renting_cost_usd") * RATE), val(r.metrics.get("total_requests"))};
    }

    static String val(Double d) {
        if (d == null) return "";
        return d == Math.rint(d) ? String.valueOf(d.longValue()) : String.valueOf(d);
    }

    static String fmt(double d) { return String.format(Locale.ROOT, "%.2f", d); }

    static String str(Object o) { return o == null ? "" : String.valueOf(o); }

    static String table(List<String[]> rows) {
        StringBuilder s = new StringBuilder();
        s.append("| ").append(String.join(" | ", rows.get(0))).append(" |\n|");
        for (int i = 0; i < rows.get(0).length; i++) s.append("---|");
        s.append('\n');
        for (String[] r : rows.subList(1, rows.size())) s.append("| ").append(String.join(" | ", Arrays.asList(r))).append(" |\n");
        return s.toString();
    }
}
